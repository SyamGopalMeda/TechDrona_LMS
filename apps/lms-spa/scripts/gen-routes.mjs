// Generates src/spa/routes.gen.tsx (the React Router route tree) from the Next App Router folder
// structure in src/app: nested layouts, route groups `(x)` (no URL segment), dynamic segments
// `[x]` → `:x`, catch-alls `[...x]` → `*` (param `x: string[]`), error.tsx / loading.tsx
// boundaries per segment, the root not-found / global-error, and next.config.ts redirects.
// Route handlers (route.ts) are not pages: the API function / Hosting serve them.
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "src", "app");
const outFile = join(root, "src", "spa", "routes.gen.tsx");

const SPECIAL = ["layout", "error", "loading"];
let pageCount = 0;
const pagePaths = [];

const has = (dir, name) => existsSync(join(dir, `${name}.tsx`));
const imp = (rel, name) => `() => import("@/app/${rel ? `${rel}/` : ""}${name}")`;

function segmentPath(name) {
  if (/^\(.*\)$/.test(name)) return { path: undefined };
  let m = name.match(/^\[\[\.\.\.(\w+)\]\]$/);
  if (m) return { path: "*", catchAll: m[1], optional: true };
  m = name.match(/^\[\.\.\.(\w+)\]$/);
  if (m) return { path: "*", catchAll: m[1] };
  m = name.match(/^\[(\w+)\]$/);
  if (m) return { path: `:${m[1]}` };
  return { path: name };
}

function childDirs(dir) {
  return readdirSync(dir)
    .filter((n) => statSync(join(dir, n)).isDirectory())
    .sort();
}

/** Route object source for directory `rel` (relative to src/app), or null when it has no pages. */
function node(rel, name, urlPrefix, indent) {
  const dir = join(appDir, rel);
  const seg = segmentPath(name);
  const pad = " ".repeat(indent);
  const url = seg.path === undefined ? urlPrefix : `${urlPrefix}/${seg.path}`;
  const children = [];
  if (has(dir, "page")) {
    pageCount += 1;
    pagePaths.push(url || "/");
    const ca = seg.catchAll ? `, ${JSON.stringify(seg.catchAll)}` : "";
    children.push(`${pad}  { index: true, lazy: lazyPage(${imp(rel, "page")}${ca})${seg.catchAll ? `, handle: { catchAll: ${JSON.stringify(seg.catchAll)} }` : ""} },`);
  }
  for (const c of childDirs(dir)) {
    const src = node(rel ? `${rel}/${c}` : c, c, url, indent + 2);
    if (src) children.push(src);
  }
  if (!children.length) return null;
  const specials = SPECIAL.filter((s) => has(dir, s));
  const parts = [];
  if (seg.path !== undefined) parts.push(`path: ${JSON.stringify(seg.path)}`);
  if (seg.catchAll) parts.push(`handle: { catchAll: ${JSON.stringify(seg.catchAll)} }`);
  if (specials.length) parts.push(`lazy: lazySegment({ ${specials.map((s) => `${s}: ${imp(rel, s)}`).join(", ")} })`);
  return `${pad}{\n${pad}  ${parts.join(`,\n${pad}  `)}${parts.length ? "," : ""}\n${pad}  children: [\n${children.join("\n")}\n${pad}  ],\n${pad}},`;
}

const top = [];
if (has(appDir, "page")) {
  pageCount += 1;
  pagePaths.push("/");
  top.push(`      { index: true, lazy: lazyPage(${imp("", "page")}) },`);
}
for (const c of childDirs(appDir)) {
  const src = node(c, c, "", 6);
  if (src) top.push(src);
}

const source = `/* eslint-disable */
// GENERATED by scripts/gen-routes.mjs from src/app — do not edit. ${pageCount} pages.
import type { RouteObject } from "react-router";
import * as RootLayout from "@/app/layout";
import * as RootNotFound from "@/app/not-found";
${has(appDir, "error") ? 'import * as RootError from "@/app/error";\n' : ""}${has(appDir, "global-error") ? 'import * as GlobalError from "@/app/global-error";\n' : ""}import { lazyPage, lazySegment, redirectRoute, rootRoute } from "./runtime";

export const PAGE_COUNT = ${pageCount};

export const routes: RouteObject[] = [
  rootRoute({
    layout: RootLayout,
    notFound: RootNotFound,
${has(appDir, "error") ? "    error: RootError,\n" : ""}${has(appDir, "global-error") ? "    globalError: GlobalError,\n" : ""}    // apps/web/next.config.ts redirects() (also configured on Firebase Hosting).
    redirects: [
      redirectRoute("admin/security", () => "/security"),
      redirectRoute("admin/security/*", (p) => \`/security/\${p["*"] ?? ""}\`),
      redirectRoute("verify/certificate/:id", (p) => \`/verify/\${encodeURIComponent(p.id ?? "")}\`),
    ],
    children: [
${top.join("\n")}
    ],
  }),
];
`;

writeFileSync(outFile, source);
writeFileSync(join(root, "scripts", "routes-report.json"), `${JSON.stringify({ pages: pageCount, paths: pagePaths.sort() }, null, 2)}\n`);
console.log(`[gen-routes] ${pageCount} pages → src/spa/routes.gen.tsx`);
