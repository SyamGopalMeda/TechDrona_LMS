"""DEV / DEMO ONLY — print (or write) the Playwright ``@integration`` env for the seeded fixtures.

Run after all seeds:  ``python -m app.seeds.e2e_env [--out ../web/.env.e2e.local]``

Read-only: looks up the ids the seeds generated (the L4 case, the E2E timed test) and combines
them with the fixed dev constants (accounts, the shared ``DEV_PASSWORD``, the DEV-ONLY TOTP
secrets). Output is ``KEY=VALUE`` lines; ``apps/web/playwright.config.ts`` loads
``apps/web/.env.e2e.local`` when present (gitignored via ``.env.*``). Refuses in production.
"""

from __future__ import annotations

import argparse
import asyncio
import sys
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.core.config import get_settings
from app.core.db import make_engine, system_context
from app.core.models_registry import import_all_models
from app.modules.assessments.models import Test
from app.modules.identity.models import User
from app.modules.security.models import SecurityCase
from app.seeds import dev_users, e2e_demo, security_demo, seeds_allowed

import_all_models()

BASE_URL = "http://localhost:13000"
MAILPIT_URL = "http://localhost:8025"
FREE_COURSE_SLUG = "demo-dsa-free"


class ProductionRefused(RuntimeError):
    pass


def guard() -> None:
    if not seeds_allowed():
        raise ProductionRefused("e2e_env refuses to run outside APP_ENV local/dev/test")


def _acct(prefix: str, local: str, *, totp: bool = False) -> list[tuple[str, str]]:
    out = [
        (f"E2E_{prefix}_IDENTIFIER", f"{local}@{dev_users.DOMAIN}"),
        (f"E2E_{prefix}_PASSWORD", dev_users.DEV_PASSWORD),
    ]
    if totp:
        out.append((f"E2E_{prefix}_TOTP_SECRET", dev_users.DEV_TOTP_SECRETS[local]))
    return out


async def values(session: AsyncSession) -> list[tuple[str, str]]:
    guard()
    await system_context(session, "seed.e2e_env")
    case_id = (
        await session.execute(
            select(SecurityCase.id)
            .join(User, User.id == SecurityCase.user_id)
            .where(User.email == security_demo.SUSPENDED, SecurityCase.level == 4)
            .order_by(SecurityCase.created_at.desc())
            .limit(1)
        )
    ).scalar_one_or_none()
    test_id = (
        await session.execute(select(Test.id).where(Test.slug == e2e_demo.E2E_TEST_SLUG))
    ).scalar_one_or_none()
    if case_id is None or test_id is None:
        raise RuntimeError("fixtures missing - run security_demo and e2e_demo first")
    return [
        ("E2E_INTEGRATION", "1"),
        ("E2E_BASE_URL", BASE_URL),
        ("MAILPIT_URL", MAILPIT_URL),
        *_acct("STUDENT", "student"),
        *_acct("RESTRICTED", "restricted.student"),
        *_acct("REVERIFY", "reverify.student"),
        *_acct("REVIEWER_A", "security", totp=True),
        *_acct("REVIEWER_B", "security2", totp=True),
        *_acct("EVALUATOR", "evaluator", totp=True),
        *_acct("TRAINER", "trainer", totp=True),
        # finance desk = an Admin account since the single-company role consolidation (D2).
        *_acct("FINANCE", "finance", totp=True),
        *_acct("CONTENT", "content", totp=True),
        *_acct("ADMIN", "admin", totp=True),
        ("E2E_L4_CASE_ID", str(case_id)),
        ("E2E_TEST_ID", str(test_id)),
        ("E2E_FREE_COURSE_SLUG", FREE_COURSE_SLUG),
    ]


def render(pairs: list[tuple[str, str]]) -> str:
    head = "# DEV/DEMO ONLY - generated by scripts/reset-dev-data.ps1 (app.seeds.e2e_env). Do not commit.\n"
    return head + "".join(f"{k}={v}\n" for k, v in pairs)


async def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, help="write to this file instead of stdout")
    args = ap.parse_args(argv)
    guard()
    engine = make_engine(get_settings().DATABASE_URL)
    try:
        async with async_sessionmaker(engine, expire_on_commit=False)() as session, session.begin():
            text = render(await values(session))
    finally:
        await engine.dispose()
    if args.out:
        args.out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {args.out}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(asyncio.run(main()))
