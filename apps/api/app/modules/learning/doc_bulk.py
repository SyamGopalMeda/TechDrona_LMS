MAX_VALIDATE_ROWS = 1000
MAX_ISSUE_ROWS = 200
MAX_PDF_IDS = 20
MAX_ENROLMENTS = 500
ISSUE_BUDGET_S = 40.0
PDF_BUDGET_S = 40.0
MOBILE_MSG = "Mobile: use digits only, optionally with + and the country code."
ROW_FAILED = "Could not issue this row."
MOBILE_RE = re.compile(r"^\+?[0-9][0-9 \-]{5,18}[0-9]$")
_FILENAME_BAD = re.compile(r'[\\/:*?"<>|\x00-\x1f]+')


def email_ready() -> bool:
    """Email really reaches people (``notifications.email_integrated``). While it does not (console
    / memory provider, local Mailpit), the UI generates the documents for download instead."""
    from app.modules.notifications.public import email_integrated

    return email_integrated()


def bulk_tag(doc: IssuedDocument) -> dict[str, Any]:
    tag = (doc.content or {}).get("bulk")
    return tag if isinstance(tag, dict) else {}


def _row_no(row: dict[str, Any], i: int) -> int:
    n = row.get("row")
    return int(n) if isinstance(n, int) and n > 0 else i + 1


def _recipient(row: dict[str, Any]) -> dict[str, str]:
    return docs.clean_recipient({k: row.get(k) for k in ("name", "email", "college", "reg_no")})


def check_row(
    doc_type: str,
    row: dict[str, Any],
    *,
    settings: dict[str, Any],
    override: dict[str, Any] | None,
    issue_date: date,
    site_url: str,
) -> dict[str, Any]:
    """Everything wrong with one row, without touching the store (the issue path re-checks)."""
    rcp = _recipient(row)
    errors: list[str] = []
    fields: dict[str, str] = {}
    for k, v in (row.get("fields") or {}).items():
        if k not in dd.DOC_TYPES[doc_type]["fields"]:
            continue
        try:
            fields.update(dd.clean_fields(doc_type, {k: v}))
        except ValueError as e:
            errors.append(str(e))
    mobile = " ".join(str(row.get("mobile") or "").split())
    if mobile and not MOBILE_RE.match(mobile):
        errors.append(MOBILE_MSG)
    if doc_type == "cert_completion" and row.get("enrolment_id"):
        errors.append(
            "Course completion certificates for LMS enrolments are issued from the Due tab; "
            "remove the enrolment for this row."
        )
    missing = dd.missing_fields(doc_type, fields, rcp)
    leftovers: list[str] = []
    if not missing and not errors:
        # compose()'s strict check, with the template override read once for the whole upload
        ref = f"TD-{dd.PREFIXES[doc_type]}-{issue_date.year}-PREVEW"
        values = dd.placeholder_values(
            doc_type=doc_type, recipient=rcp, fields=fields, settings=settings, ref_no=ref,
            cert_no=ref if dd.is_certificate(doc_type) else "", issue_date=issue_date, site_url=site_url,
        )  # fmt: skip
        leftovers = dd.leftover_tokens(
            dd.doc_paragraphs(doc_type, values, override),
            dd.fill(dd.DOC_TYPES[doc_type]["subject"], values),
            dd.letter_sections(doc_type, values, override),
            dd.render_extras(doc_type, fields, rcp),
            rcp.get("name"),
        )
        if leftovers:
            errors.append(f"Template text left in the wording: {', '.join(leftovers[:4])}.")
    return {"recipient": rcp, "fields": fields, "errors": errors, "missing": missing, "mobile": mobile}


async def _holders(session: AsyncSession, doc_type: str) -> dict[str, str]:
    """lower(email) -> ref_no of the valid documents of this type already issued."""
    if fss.fs():
        rows = await fss.find(
            session,
            IssuedDocument,
            filters=(("doc_type", "==", doc_type), ("status", "==", "valid")),
            job="learning.documents",
        )
        pairs = [(d.recipient_email, d.ref_no) for d in rows]
    else:
        pairs = list(
            (
                await session.execute(
                    select(IssuedDocument.recipient_email, IssuedDocument.ref_no).where(
                        IssuedDocument.doc_type == doc_type, IssuedDocument.status == "valid"
                    )
                )
            ).all()
        )
    return {(e or "").lower(): r for e, r in pairs if e}


async def validate(
    session: AsyncSession, *, doc_type: str, rows: list[dict[str, Any]], issue_date: date | None
) -> dict[str, Any]:
    if doc_type not in dd.DOC_TYPES:
        raise ProblemError("validation_failed", detail="Unknown document type.")
    st = await docs.load_settings(session)
    override = await docs.template_override(session, "document", doc_type)
    day = issue_date or ist_date(utcnow())
    site = docs._site_url()
    holders = await _holders(session, doc_type)
    short = dd.DOC_TYPES[doc_type]["short"]
    seen: dict[str, int] = {}
    out = []
    for i, row in enumerate(rows):
        no = _row_no(row, i)
        c = check_row(doc_type, row, settings=st, override=override, issue_date=day, site_url=site)
        email = c["recipient"]["email"]
        warnings: list[str] = []
        if email and dd.EMAIL_RE.match(email):
            if email in seen:
                c["errors"].append(f"Same email as row {seen[email]}: one document per recipient.")
            else:
                seen[email] = no
            if email in holders:
                warnings.append(f"Already has a valid {short.lower()} ({holders[email]}).")
        out.append(
            {
                "row": no,
                "name": c["recipient"]["name"],
                "email": email,
                "ok": not c["errors"] and not c["missing"],
                "errors": c["errors"],
                "missing": c["missing"],
                "warnings": warnings,
                "fields": c["fields"],
            }
        )
    ok = sum(1 for r in out if r["ok"])
    return {
        "doc_type": doc_type,
        "total": len(out),
        "ok": ok,
        "failed": len(out) - ok,
        "settings_problem": dd.settings_problem(st) or None,
        "email_ready": email_ready(),
        "auto_send": await certs.auto_send_enabled(session),
        "rows": out,
    }


def _uuid(v: Any) -> uuid.UUID | None:
    if v in (None, ""):
        return None
    return v if isinstance(v, uuid.UUID) else uuid.UUID(str(v))


async def issue_rows(
    session: AsyncSession,
    actor: Any,
    *,
    doc_type: str,
    rows: list[dict[str, Any]],
    issue_date: date | None,
    email: str,
    bulk_id: uuid.UUID,
    label: str = "",
    started: float | None = None,
) -> dict[str, Any]:
    """Issue each row (own savepoint; failures are reported per row). ``email``: ``outbox`` |
    ``none``. Rows not reached within ``ISSUE_BUDGET_S`` come back as ``deferred``."""
    from app.modules.identity import public as identity_public

    if doc_type not in dd.DOC_TYPES:
        raise ProblemError("validation_failed", detail="Unknown document type.")
    st = await docs.load_settings(session)
    problem = dd.settings_problem(st)
    if problem:
        raise ProblemError("invalid_state_transition", detail=problem, reason="settings")
    t0 = started if started is not None else time.monotonic()
    emails = [str(r.get("email") or "").strip().lower() for r in rows if not r.get("user_id")]
    users = await identity_public.users_by_emails(session, [e for e in emails if dd.EMAIL_RE.match(e)])
    results: list[dict[str, Any]] = []
    for i, row in enumerate(rows):
        no = _row_no(row, i)
        if time.monotonic() - t0 > ISSUE_BUDGET_S:
            results.append({"row": no, "status": "deferred"})
            continue
        rcp = _recipient(row)
        try:
            user_id = _uuid(row.get("user_id"))
            if user_id is None and rcp["email"] in users:
                user_id = users[rcp["email"]].id
            enrolment_id = _uuid(row.get("enrolment_id"))
            mobile = " ".join(str(row.get("mobile") or "").split())
            if mobile and not MOBILE_RE.match(mobile):
                raise ProblemError("validation_failed", detail=MOBILE_MSG)
            async with certs.savepoint(session):
                doc = await docs.issue_document(
                    session,
                    actor,
                    doc_type=doc_type,
                    recipient=rcp,
                    fields=row.get("fields") or {},
                    issue_date=issue_date,
                    user_id=user_id,
                    enrolment_id=enrolment_id,
                    batch_id=_uuid(row.get("batch_id")),
                    course_id=_uuid(row.get("course_id")),
                    origin="manual",
                    bulk={"id": str(bulk_id), "row": no, "label": label[:120]},
                )
        except ProblemError as e:
            missing = e.ext.get("missing") if isinstance(e.ext.get("missing"), list) else None
            results.append(
                {"row": no, "status": "failed", "error": e.detail, "code": e.code, "missing": missing}
            )
            continue
        except Exception as e:  # never abort the run for one row (rendering / store bug)
            log.warning("bulk_document_failed", row=no, error=type(e).__name__)
            results.append({"row": no, "status": "failed", "error": ROW_FAILED, "code": "internal_error"})
            continue
        email_status: str | None = None
        if email == "outbox":
            try:
                ob = await docs.queue_email(session, doc, origin="manual")
                email_status = ob.status if ob is not None else None
            except Exception as e:  # the document stands; the email can be queued from the register
                log.warning("bulk_document_email_failed", document_id=str(doc.id), error=type(e).__name__)
                email_status = "error"
        results.append(
            {
                "row": no,
                "status": "issued",
                "document_id": str(doc.id),
                "ref_no": doc.ref_no,
                "verify_url": f"/verify/{doc.ref_no}",
                "name": doc.recipient_name,
                "email": doc.recipient_email,
                "user_linked": doc.user_id is not None,
                "pdf_available": doc.pdf_s3_key is not None,
                "email_status": email_status,
            }
        )
    counts = {s: sum(1 for r in results if r["status"] == s) for s in ("issued", "failed", "deferred")}
    if counts["issued"] or counts["failed"]:
        await audit(
            session, actor, "documents.bulk_issue", "issued_document_bulk", bulk_id,
            after={"doc_type": doc_type, "label": label[:120], "email": email, **counts},
        )  # fmt: skip
    return {"bulk_id": str(bulk_id), "doc_type": doc_type, **counts, "results": results}


async def run_documents(
    session: AsyncSession, bulk_id: uuid.UUID, doc_type: str | None = None
) -> list[IssuedDocument]:
    """The documents of one bulk run, in spreadsheet row order."""
    bid = str(bulk_id)
    if fss.fs():
        filters: tuple[fss.Filter, ...] = (("doc_type", "==", doc_type),) if doc_type else ()
        rows = await fss.find(
            session,
            IssuedDocument,
            filters=filters,
            where=lambda d: bulk_tag(d).get("id") == bid,
            job="learning.documents",
        )
    else:
        q = select(IssuedDocument).where(IssuedDocument.content["bulk"]["id"].astext == bid)
        if doc_type:
            q = q.where(IssuedDocument.doc_type == doc_type)
        rows = list((await session.execute(q)).scalars())
    rows.sort(key=lambda d: (int(bulk_tag(d).get("row") or 0), str(d.id)))
    return rows


def pdf_filename(doc: IssuedDocument) -> str:
    name = _FILENAME_BAD.sub(" ", doc.recipient_name or "").strip()[:80]
    return f"{doc.ref_no}{' - ' + name if name else ''}.pdf"


async def pdfs(session: AsyncSession, ids: list[uuid.UUID]) -> dict[str, Any]:
    """The PDFs (base64) of up to ``MAX_PDF_IDS`` documents, for the browser's ZIP. Each copy is
    recorded as handed out (``pdf_for_handout``), as a download is."""
    t0 = time.monotonic()
    files: list[dict[str, Any]] = []
    skipped: list[dict[str, str]] = []
    for did in dict.fromkeys(ids):
        if time.monotonic() - t0 > PDF_BUDGET_S:
            skipped.append({"id": str(did), "reason": "deferred"})
            continue
        d = await fss.get(session, IssuedDocument, did)
        if d is None:
            skipped.append({"id": str(did), "reason": "not_found"})
            continue
        if d.status != "valid":
            skipped.append({"id": str(did), "reason": d.status})
            continue
        data = await docs.pdf_for_handout(session, d)
        files.append(
            {
                "id": str(d.id),
                "ref_no": d.ref_no,
                "filename": pdf_filename(d),
                "pdf_base64": base64.b64encode(data).decode("ascii"),
            }
        )
    return {"files": files, "skipped": skipped}


async def enrolment_rows(
    session: AsyncSession, *, batch_id: uuid.UUID | None, course_id: uuid.UUID | None
) -> list[dict[str, Any]]:
    """Students of a batch and/or course for the "pick students" source (name, email, course,
    status); the browser then fills each picked one through ``GET /admin/documents/prefill``."""
    from app.modules.identity import public as identity_public
    from app.modules.learning.models import Enrolment

    if batch_id is None and course_id is None:
        raise ProblemError("validation_failed", detail="Choose a batch or a course.")
    if fss.fs():
        filters: list[fss.Filter] = []
        if batch_id is not None:
            filters.append(("batch_id", "==", batch_id))
        if course_id is not None:
            filters.append(("course_id", "==", course_id))
        enrs = await fss.find(session, Enrolment, filters=filters, limit=MAX_ENROLMENTS)
    else:
        q = select(Enrolment)
        if batch_id is not None:
            q = q.where(Enrolment.batch_id == batch_id)
        if course_id is not None:
            q = q.where(Enrolment.course_id == course_id)
        enrs = list((await session.execute(q.limit(MAX_ENROLMENTS))).scalars())
    cards = await identity_public.user_cards(session, {e.user_id for e in enrs})
    titles = await certs.course_titles(session, {e.course_version_id for e in enrs})
    out = []
    for e in enrs:
        card = cards.get(e.user_id)
        email = (card.email if card else None) or ""
        out.append(
            {
                "enrolment_id": str(e.id),
                "user_id": str(e.user_id),
                "name": ((card.full_name or card.display_name) if card else None) or email.split("@")[0],
                "email": email.lower(),
                "mobile": (card.phone_e164 if card else None) or "",
                "course_id": str(e.course_id),
                "course_title": titles.get(e.course_version_id) or "",
                "batch_id": str(e.batch_id) if e.batch_id else None,
                "status": e.status,
            }
        )
    out.sort(key=lambda r: (str(r["course_title"]), str(r["name"]).lower()))
    return out
