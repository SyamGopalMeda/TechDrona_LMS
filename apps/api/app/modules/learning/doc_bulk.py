"""Bulk documents: issue many offer letters / certificates / LORs from a spreadsheet (or a list of
picked students) in Admin > Certificates & documents > Create & send > Bulk.

The browser parses the ``.xlsx`` / ``.csv`` (SheetJS) and sends rows as JSON; nothing here reads
spreadsheets. Each row is validated and issued with the single-document rules
(``documents.issue_document``): same fields, same refusal of missing details / leftover template
text / missing settings, same reference numbers, PDFs and verification pages.

* ``validate``: per row ``clean_fields`` (every bad cell, not only the first) + ``missing_fields`` +
  leftover template text, duplicate recipients in the upload (an error) and recipients who already
  hold a valid document of this type (a warning), plus the settings problem.
* ``issue_rows``: issues each row in its own savepoint; a failing row never aborts the others.
  Rows are tagged ``content["bulk"] = {id, row, label}`` (``bulk_id`` = the run, generated by the
  browser) so the run can be listed again; no schema change. A recipient email that belongs to an
  LMS account links the document to that user. Emails: ``outbox`` queues one email per document
  following the auto-send setting (sent by the outbox relay, or waiting in the approval queue);
  ``none`` only generates the documents (download the ZIP / share the verification links).
* Time budget: the Hosting -> Functions request limit is 60 s, so a call stops issuing after
  ``ISSUE_BUDGET_S`` and returns the remaining rows as ``deferred``; the browser sends rows in
  chunks of 25 (with progress) and re-sends deferred rows in the next call.
"""

